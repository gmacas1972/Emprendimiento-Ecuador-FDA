# 2. Read the typology matrix generated by the FDA script
# (Assuming you are running this from the project root directory)
if(!file.exists("outputs/tables/typology_matrix_46curves.csv")) {
  stop("Error: Typology matrix not found. Please run 02_fda_analysis.R first.")
}

matrix_final <- read.csv("outputs/tables/typology_matrix_46curves.csv")

# 3. Prepare data: extract province names and filter Urban areas for spatial analysis
# (We use Urban areas as they represent the main economic hubs of each province)
mapa_datos <- matrix_final %>%
  mutate(
    # Remove " (Urb)" and " (Rur)" from the Curve column
    prov_name = str_remove(Curve, " \\(Urb\\)| \\(Rur\\)"),
    cluster_income = as.numeric(Income)
  ) %>%
  filter(grepl("\\(Urb\\)", Curve)) %>% # Keep only Urban to have 1 point per province
  select(prov_name, cluster_income) %>%
  # Fix province name mismatches between ENEMDU and IGM shapefile
  mutate(prov_name = case_when(
    prov_name == "Santo Domingo" ~ "Santo Domingo de los Tsáchilas",
    TRUE ~ prov_name
  ))

# 4. Download the official shapefile of Ecuador
cat(">>> Downloading Ecuador shapefile from IGM...\n")
mapa_ecuador <- read_provincias()

# 5. Join spatial data with clusters (CORREGIDO)
cat(">>> Joining spatial data...\n")
mapa_ecuador <- mapa_ecuador %>%
  rename(prov_name = matches("DPA_DESPRO|provincia|nombre", ignore.case = TRUE))

mapa_datos <- mapa_datos %>%
  mutate(prov_clean = toupper(iconv(prov_name, to = "ASCII//TRANSLIT")))

mapa_ecuador <- mapa_ecuador %>%
  mutate(prov_clean = toupper(iconv(prov_name, to = "ASCII//TRANSLIT")))

datos_sf <- mapa_ecuador %>%
  left_join(mapa_datos, by = "prov_clean") %>%
  filter(!is.na(cluster_income))

# 6. Create Spatial Weights Matrix (K-Nearest Neighbors)
coords <- st_coordinates(st_centroid(st_transform(datos_sf, 32717)))
nb <- knn2nb(knearneigh(coords, k = 4))
listw <- nb2listw(nb, style = "W", zero.policy = TRUE)

# 7. Calculate Moran's I
cat(">>> Calculating Moran's I...\n")
moran_res <- moran.test(datos_sf$cluster_income, listw, zero.policy = TRUE)

# Print and save results
print(moran_res)
capture.output(print(moran_res), file = "outputs/tables/spatial_moran_test.txt")

# 8. Generate a spatial map of clusters (Bonus plot for your paper)
png("outputs/figures/fig_spatial_clusters.png", width = 800, height = 1000, res = 150)
plot(datos_sf["cluster_income"], 
     main = "Spatial Distribution of Income Clusters (Urban Areas)",
     col = c("lightblue", "orange", "darkred")[datos_sf$cluster_income],
     border = "white", lwd = 0.5)
dev.off()

cat("\n=========================================================\n")
cat("SPATIAL VALIDATION COMPLETED!\n")
